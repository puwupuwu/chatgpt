import {test,expect} from '@playwright/test';
import {readFile} from 'node:fs/promises';
import {fixture,png} from '../fixture.js';
import {listContent} from '../../src/content.js';
test('existing content editing survives export, undo, image replace and geometry changes',async({page})=>{
 test.setTimeout(90000);
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto('/');
 await page.locator('#file').setInputFiles({name:'invoice.pdf',mimeType:'application/pdf',buffer:Buffer.from(await fixture())});
 await expect(page.locator('#export')).toBeEnabled();
 await page.locator('[data-tool="select"]').click();
 const textObject=page.locator('.object-box').filter({hasText:''});
 await expect(page.locator('#status')).toContainText('editable objects',{timeout:30000});
 await page.getByRole('button',{name:'Text: Original invoice',exact:true}).click();
 await page.locator('#objectText').fill('Updated invoice');
 await page.locator('#applyObject').click();
 await expect(page.locator('#status')).toContainText('Content updated');
 await page.locator('#undo').click();await expect(page.getByRole('button',{name:'Text: Original invoice',exact:true})).toBeVisible();
 await page.locator('#redo').click();await expect(page.getByRole('button',{name:'Text: Updated invoice',exact:true})).toBeVisible();
 await expect(page.locator('#export')).toBeEnabled();
 await page.locator('.object-box[data-object-type="image"]').first().click();
 await page.locator('#objectX').fill('120');await page.locator('#objectY').fill('150');await page.locator('#objectW').fill('45');await page.locator('#objectH').fill('35');await page.locator('#applyObject').click();
 await expect(page.locator('#status')).toContainText('Content updated');
 await page.locator('.object-box[data-object-type="image"]').first().click();
 const chooser=page.waitForEvent('filechooser');await page.locator('#replaceImage').click();await (await chooser).setFiles({name:'blue.png',mimeType:'image/png',buffer:png(20,50,200)});
 await expect(page.locator('#status')).toContainText('Content updated');await expect(page.locator('#export')).toBeEnabled();
 await page.locator('.object-box[data-object-type="shape"]').first().click();await page.locator('#removeObject').click();
 await expect(page.locator('#status')).toContainText('Content updated');
 await page.locator('#insertShape').click();await expect(page.locator('#status')).toContainText('Content updated');
 await page.screenshot({path:'test-results/content-editor.png',fullPage:true});
 const wait=page.waitForEvent('download');await page.locator('#export').click();const download=await wait,bytes=await readFile(await download.path());
 const result=await listContent(bytes,0),texts=result.items.filter(i=>i.type==='text').map(i=>i.text).join(' ');
 expect(texts).toContain('Updated invoice');expect(texts).not.toContain('Original invoice');expect(texts).toContain('Keep this line');
 const images=result.items.filter(i=>i.type==='image');expect(images).toHaveLength(2);expect(images[0].bounds[0]).toBeCloseTo(120,0);
 expect(result.items.filter(i=>i.type==='shape')).toHaveLength(1);expect(errors).toEqual([]);
});
