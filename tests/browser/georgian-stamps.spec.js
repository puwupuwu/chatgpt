import {test,expect} from '@playwright/test';
import {readFile} from 'node:fs/promises';
import {listContent} from '../../src/content.js';
import {png} from '../fixture.js';
test('Georgian text and reusable stamps persist in exported PDF',async({page})=>{
 test.setTimeout(120000);
 await page.goto('/');await page.locator('#sample').click();await expect(page.locator('#export')).toBeEnabled();
 await page.locator('#ink').click({position:{x:80,y:180}});
 await page.locator('#textValue').fill('გამარჯობა საქართველო');
 await page.locator('#addText').click();await expect(page.locator('#export')).toBeEnabled();
 await page.locator('[data-tool="select"]').click();
 await page.getByRole('button',{name:'Text: გამარჯობა საქართველო',exact:true}).click();
 const inline=page.getByRole('textbox',{name:'Edit text on page',exact:true});
 await inline.fill('შეცვლილი ქართული ტექსტი');await inline.press('Control+Enter');
 await expect(page.locator('#status')).toContainText('Content updated');
 await page.locator('#openStamps').click();
 await page.locator('#stampText').fill('დამტკიცებულია');
 await page.locator('#stampDateEnabled').check();await page.locator('#stampDate').fill('2026-10-31');
 await expect(page.locator('#placeStamp')).toBeEnabled();
 await page.locator('#placeStamp').click();await expect(page.locator('#status')).toContainText('Click on the page');
 await page.locator('#ink').click({position:{x:200,y:320}});
 await expect(page.locator('#status')).toContainText('Content updated');
 await expect(page.locator('.object-box[data-object-type="image"]')).toHaveCount(1);
 await page.locator('#undo').click();await expect(page.locator('.object-box[data-object-type="image"]')).toHaveCount(0);
 await page.locator('#redo').click();await expect(page.locator('.object-box[data-object-type="image"]')).toHaveCount(1);
 await page.locator('#openStamps').click();
 await expect(page.locator('#savedStamps option')).toHaveCount(2);
 const saved=await page.locator('#savedStamps option').nth(1).getAttribute('value');
 await page.locator('#savedStamps').selectOption(saved);
 await expect(page.locator('#placeStamp')).toBeEnabled();await page.locator('#placeStamp').click();
 await page.locator('#ink').click({position:{x:200,y:450}});await expect(page.locator('#status')).toContainText('Content updated');
 await expect(page.locator('.object-box[data-object-type="image"]')).toHaveCount(2);
 const wait=page.waitForEvent('download');await page.locator('#export').click();const file=await wait,bytes=await readFile(await file.path());
 const scene=await listContent(bytes,0);
 expect(scene.items.some(i=>i.text==='შეცვლილი ქართული ტექსტი')).toBeTruthy();
 expect(scene.items.filter(i=>i.type==='image')).toHaveLength(2);
 await page.reload();await page.locator('#sample').click();await expect(page.locator('#openStamps')).toBeEnabled();
 await page.locator('#openStamps').click();await expect(page.locator('#savedStamps option')).toHaveCount(2);
 await page.screenshot({path:'test-results/georgian-stamps.png',fullPage:true});
});
test('custom stamp images can be uploaded and placed',async({page})=>{
 await page.goto('/');await page.locator('#sample').click();await expect(page.locator('#openStamps')).toBeEnabled();
 await page.locator('#openStamps').click();
 await page.locator('#stampImageFile').setInputFiles({name:'seal.png',mimeType:'image/png',buffer:png(20,40,150)});
 await expect(page.locator('#stampText')).toHaveValue('seal');
 await expect(page.locator('#placeStamp')).toBeEnabled();await page.locator('#placeStamp').click();
 await page.locator('#ink').click({position:{x:60,y:270}});
 await expect(page.locator('#status')).toContainText('Content updated');
 await expect(page.locator('.object-box[data-object-type="image"]')).toHaveCount(1);
});
