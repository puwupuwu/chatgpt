import {test,expect} from '@playwright/test';
import {readFile} from 'node:fs/promises';
import {fixture} from '../fixture.js';
import {listContent} from '../../src/content.js';
test('edits individual letters inline with caret, selection, cancel, undo and export',async({page})=>{
 test.setTimeout(90000);
 await page.goto('/');
 await page.locator('#file').setInputFiles({name:'invoice.pdf',mimeType:'application/pdf',buffer:Buffer.from(await fixture())});
 await expect(page.locator('#export')).toBeEnabled();
 await page.locator('[data-tool="select"]').click();
 await page.getByRole('button',{name:'Text: Original invoice',exact:true}).click();
 const editor=page.getByRole('textbox',{name:'Edit text on page',exact:true});
 await expect(editor).toBeFocused();
 await editor.press('Control+Home');
 for(let i=0;i<8;i++)await editor.press('ArrowRight');
 await page.keyboard.insertText('X');
 await expect(editor).toHaveText('OriginalX invoice');
 await editor.press('Backspace');
 await expect(editor).toHaveText('Original invoice');
 await editor.press('Shift+End');
 await page.keyboard.insertText(' receipt');
 await expect(editor).toHaveText('Original receipt');
 await editor.press('Control+Enter');
 await expect(editor).toHaveCount(0);
 await expect(page.locator('#status')).toContainText('Content updated');
 await page.locator('#undo').click();
 await expect(page.getByRole('button',{name:'Text: Original invoice',exact:true})).toBeVisible();
 await page.locator('#redo').click();
 await expect(page.getByRole('button',{name:'Text: Original receipt',exact:true})).toBeVisible();
 await page.getByRole('button',{name:'Text: Original receipt',exact:true}).click();
 await editor.press('Control+End');await page.keyboard.insertText(' discarded');
 await editor.press('Escape');
 await expect(editor).toHaveCount(0);await expect(page.locator('#export')).toBeEnabled();
 const wait=page.waitForEvent('download');await page.locator('#export').click();const download=await wait;
 const output=await readFile(await download.path()),scene=await listContent(output,0);
 const text=scene.items.filter(i=>i.type==='text').map(i=>i.text).join(' ');
 expect(text).toContain('Original receipt');expect(text).not.toContain('Original invoice');expect(text).not.toContain('discarded');expect(text).toContain('Keep this line');
});
